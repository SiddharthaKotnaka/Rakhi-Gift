let lightboxIndex = 0;
let previousFocus = null;

function openLightbox(index) {
  if (!DOM.lightbox) return;
  lightboxIndex = index;
  previousFocus = document.activeElement;
  
  DOM.lightbox.hidden = false;
  document.body.classList.add('lightbox-open');
  
  updateLightbox();
  
  if (DOM.lightboxClose) {
    DOM.lightboxClose.focus();
  }
}

function updateLightbox() {
  if (!DOM.lightbox) return;
  
  const memory = CONFIG.memories[lightboxIndex];
  if (!memory) return;
  
  if (DOM.lightboxImg) {
    DOM.lightboxImg.src = memory.image;
    DOM.lightboxImg.alt = memory.caption;
  }
  
  if (DOM.lightboxCaption) {
    DOM.lightboxCaption.textContent = `${memory.title} — ${memory.caption}`;
  }
  
  if (DOM.lightboxNum) {
    DOM.lightboxNum.textContent = `${(lightboxIndex + 1).toString().padStart(2, '0')} / ${CONFIG.memories.length.toString().padStart(2, '0')}`;
  }
  
  if (DOM.lightboxPrev) {
    DOM.lightboxPrev.style.display = lightboxIndex === 0 ? 'none' : 'block';
  }
  
  if (DOM.lightboxNext) {
    DOM.lightboxNext.style.display = lightboxIndex === CONFIG.memories.length - 1 ? 'none' : 'block';
  }
}

function closeLightbox() {
  if (!DOM.lightbox) return;
  DOM.lightbox.hidden = true;
  document.body.classList.remove('lightbox-open');
  
  if (previousFocus) {
    previousFocus.focus();
  }
}

function nextPhoto() {
  if (lightboxIndex < CONFIG.memories.length - 1) {
    lightboxIndex++;
    updateLightbox();
  }
}

function prevPhoto() {
  if (lightboxIndex > 0) {
    lightboxIndex--;
    updateLightbox();
  }
}

if (DOM.lightboxClose) DOM.lightboxClose.addEventListener('click', closeLightbox);
