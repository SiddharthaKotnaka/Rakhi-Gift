// 14. LETTER ANIMATION
// ═══════════════════════════════════════════════════════════════
function initLetter() {
  if (!DOM.envelope || !DOM.letterPaper || !DOM.letterContent || !DOM.readLetterBtn) return;
  
  const paragraphs = CONFIG.letter.split('\n\n');
  const stages = [];
  
  paragraphs.forEach(pText => {
    if (!pText.trim()) return;
    const stage = document.createElement('div');
    stage.className = 'letter-stage';
    
    // Split on single newlines for <br> within paragraphs
    const lines = pText.split('\n');
    lines.forEach((line, idx) => {
      const span = document.createElement('span');
      span.textContent = line;
      stage.appendChild(span);
      if (idx < lines.length - 1) {
        stage.appendChild(document.createElement('br'));
      }
    });
    
    DOM.letterContent.appendChild(stage);
    stages.push(stage);
  });
  
  const showLetterStages = async () => {
    for (let stage of stages) {
      if (stage.classList.contains('visible')) continue;
      stage.classList.add('visible');
      if (!prefersReducedMotion()) {
        await sleep(200);
      }
    }
  };
  
  const observer = new IntersectionObserver(async (entries) => {
    for (let entry of entries) {
      if (entry.isIntersecting) {
        DOM.envelope.classList.add('open');
        await sleep(600);
        DOM.letterPaper.classList.add('visible');
        await sleep(1200);
        showLetterStages();
        observer.unobserve(entry.target);
      }
    }
  }, { threshold: 0.2 });
  
  observer.observe(DOM.envelope);
  
  DOM.readLetterBtn.addEventListener('click', () => {
    DOM.envelope.classList.add('open');
    DOM.letterPaper.classList.add('visible');
    stages.forEach(stage => stage.classList.add('visible'));
    DOM.readLetterBtn.style.display = 'none';
  });
}

