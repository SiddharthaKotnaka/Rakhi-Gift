// 15. RAKHI INTERACTION
// ═══════════════════════════════════════════════════════════════
function initRakhi() {
  if (!DOM.rakhiElement || !DOM.rakhiThreadAnim || !DOM.rakhiMessage) return;
  
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        DOM.rakhiThreadAnim.classList.add('visible');
      }
    });
  }, { threshold: 0.5 });
  
  observer.observe(DOM.rakhiThreadAnim);
  
  DOM.rakhiElement.addEventListener('click', () => {
    if (DOM.rakhiElement.classList.contains('tapped')) return;
    
    DOM.rakhiElement.classList.add('tapped');
    
    // Vibrate
    try {
      if (navigator.vibrate) navigator.vibrate(100);
    } catch (e) {}
    
    // Spawn particles
    if (!prefersReducedMotion()) {
      for (let i = 0; i < 10; i++) {
        const p = document.createElement('span');
        p.className = 'floating-particle';
        p.textContent = Math.random() > 0.5 ? '❤️' : '✨';
        
        const offsetX = (Math.random() * 100 - 50) + 'px';
        const offsetY = (Math.random() * 100 - 50) + 'px';
        p.style.setProperty('--offset-x', offsetX);
        p.style.setProperty('--offset-y', offsetY);
        p.style.animationDelay = Math.random() * 0.3 + 's';
        
        DOM.rakhiElement.appendChild(p);
        
        setTimeout(() => p.remove(), 2000);
      }
    }
    
    DOM.rakhiMessage.hidden = false;
    
    setTimeout(() => {
      DOM.rakhiElement.classList.remove('tapped');
    }, 600);
  });
}

