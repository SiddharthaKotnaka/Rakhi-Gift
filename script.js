// 7. CONFETTI
// ═══════════════════════════════════════════════════════════════
function launchConfetti() {
  if (!DOM.confettiCanvas || prefersReducedMotion()) return;
  const canvas = DOM.confettiCanvas;
  const ctx = canvas.getContext('2d');
  
  // Resize canvas to fill window
  canvas.width = window.innerWidth;
  canvas.height = window.innerHeight;
  canvas.style.pointerEvents = 'none'; // prevent interacting
  
  const colors = ['#e2725b', '#f4c430', '#ffd700', '#ffcba4', '#800000'];
  const particles = [];
  const particleCount = 60;
  
  for (let i = 0; i < particleCount; i++) {
    particles.push({
      x: Math.random() * canvas.width,
      y: Math.random() * canvas.height - canvas.height, // start above screen
      w: Math.random() * 5 + 3, // 3-8px size
      h: Math.random() * 5 + 3,
      color: colors[Math.floor(Math.random() * colors.length)],
      vy: Math.random() * 3 + 2, // 2-5 velocity
      vx: Math.random() * 2 - 1, // -1 to 1 velocity
      rot: Math.random() * 360,
      rotSpeed: Math.random() * 10 - 5
    });
  }
  
  let animationId;
  const startTime = Date.now();
  const duration = 3000;
  
  function render() {
    ctx.clearRect(0, 0, canvas.width, canvas.height);
    
    let active = false;
    particles.forEach(p => {
      p.y += p.vy;
      p.x += p.vx;
      p.rot += p.rotSpeed;
      
      if (p.y < canvas.height) active = true;
      
      ctx.save();
      ctx.translate(p.x, p.y);
      ctx.rotate((p.rot * Math.PI) / 180);
      ctx.fillStyle = p.color;
      ctx.fillRect(-p.w / 2, -p.h / 2, p.w, p.h);
      ctx.restore();
    });
    
    if (active && Date.now() - startTime < duration) {
      animationId = requestAnimationFrame(render);
    } else {
      ctx.clearRect(0, 0, canvas.width, canvas.height);
      cancelAnimationFrame(animationId);
    }
  }
  
  render();
}

