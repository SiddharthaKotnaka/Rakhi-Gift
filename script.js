// 18. PROGRESS NAV
// ═══════════════════════════════════════════════════════════════
function initProgressNav() {
  if (!DOM.progressNav) return;
  
  const chapters = [
    { id: 'chapter-0', label: 'Start' },
    { id: 'greeting', label: 'Greeting' },
    { id: 'chapter-1', label: 'Childhood' },
    { id: 'chapter-2', label: 'Gallery' },
    { id: 'chapter-3', label: 'Fights' },
    { id: 'chapter-4', label: 'Letter' },
    { id: 'chapter-5', label: 'Rakhi' },
    { id: 'finale', label: 'Finale' }
  ];
  
  const dots = [];
  
  chapters.forEach((chapter, index) => {
    const dot = document.createElement('button');
    dot.className = 'progress-dot';
    dot.setAttribute('aria-label', `Go to ${chapter.label}`);
    
    dot.addEventListener('click', () => {
      const target = document.getElementById(chapter.id);
      if (target) {
        target.scrollIntoView({ behavior: 'smooth' });
      }
    });
    
    DOM.progressNav.appendChild(dot);
    dots.push(dot);
  });
  
  const observer = new IntersectionObserver((entries) => {
    entries.forEach(entry => {
      if (entry.isIntersecting) {
        const id = entry.target.id;
        const index = chapters.findIndex(c => c.id === id);
        if (index !== -1) {
          dots.forEach((dot, i) => {
            if (i === index) dot.classList.add('active');
            else dot.classList.remove('active');
          });
        }
      }
    });
  }, { threshold: 0.3 });
  
  chapters.forEach(c => {
    const el = document.getElementById(c.id);
    if (el) observer.observe(el);
  });
}

