// 17. MUSIC CONTROLLER
// ═══════════════════════════════════════════════════════════════
function initMusic() {
  if (!DOM.musicBtn || !DOM.musicAudio) return;
  
  let musicPlaying = false;
  let musicLoaded = false;
  
  DOM.musicAudio.addEventListener('canplaythrough', () => {
    musicLoaded = true;
  });
  
  DOM.musicAudio.addEventListener('error', () => {
    DOM.musicBtn.style.display = 'none'; // hide if file not found
  });
  
  DOM.musicBtn.addEventListener('click', () => {
    if (!musicLoaded && DOM.musicAudio.error) {
      DOM.musicBtn.style.display = 'none';
      return;
    }
    
    if (musicPlaying) {
      DOM.musicAudio.pause();
      musicPlaying = false;
      DOM.musicBtn.classList.remove('playing');
      DOM.musicBtn.setAttribute('aria-label', 'Play music');
    } else {
      DOM.musicAudio.play().then(() => {
        musicPlaying = true;
        DOM.musicBtn.classList.add('playing');
        DOM.musicBtn.setAttribute('aria-label', 'Pause music');
      }).catch(err => {
        console.error("Audio playback failed:", err);
      });
    }
  });
}

