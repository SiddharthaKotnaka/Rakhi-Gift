// 10. PHOTO REVEAL
// ═══════════════════════════════════════════════════════════════
function initPhotoReveal() {
  if (!DOM.revealPaper || !DOM.revealPhoto || !DOM.revealBtn) return;
  
  const revealMemory = CONFIG.memories[CONFIG.revealPhotoIndex];
  if (revealMemory) {
    DOM.revealPhoto.src = revealMemory.image;
    DOM.revealPhoto.alt = revealMemory.caption || 'A hidden childhood memory';
  }
  
  let isDragging = false;
  let startX = 0;
  let isRevealed = false;
  
  const doReveal = () => {
    if (isRevealed) return;
    isRevealed = true;
    DOM.revealPaper.classList.add('revealed');
    DOM.revealPaper.style.transform = 'translateX(110%)';
  };
  
  // Pointer events for dragging
  DOM.revealPaper.addEventListener('pointerdown', (e) => {
    if (isRevealed) return;
    isDragging = true;
    startX = e.clientX;
    DOM.revealPaper.style.transition = 'none'; // remove transition for smooth drag
    DOM.revealPaper.setPointerCapture(e.pointerId);
  });
  
  DOM.revealPaper.addEventListener('pointermove', (e) => {
    if (!isDragging || isRevealed) return;
    const deltaX = e.clientX - startX;
    if (deltaX > 0) {
      DOM.revealPaper.style.transform = `translateX(${deltaX}px)`;
      
      const containerWidth = DOM.revealPaper.parentElement.clientWidth;
      if (deltaX > containerWidth * 0.6) {
        doReveal();
        isDragging = false;
        DOM.revealPaper.releasePointerCapture(e.pointerId);
      }
    }
  });
  
  const snapBack = (e) => {
    if (!isDragging || isRevealed) return;
    isDragging = false;
    DOM.revealPaper.releasePointerCapture(e.pointerId);
    DOM.revealPaper.style.transition = 'transform 0.4s ease';
    DOM.revealPaper.style.transform = 'translateX(0)';
  };
  
  DOM.revealPaper.addEventListener('pointerup', snapBack);
  DOM.revealPaper.addEventListener('pointercancel', snapBack);
  
  // Reveal Button
  DOM.revealBtn.addEventListener('click', doReveal);
  
  // Keyboard access
  DOM.revealPaper.tabIndex = 0;
  DOM.revealPaper.addEventListener('keydown', (e) => {
    if (e.key === 'Enter' || e.key === ' ') {
      e.preventDefault();
      doReveal();
    }
  });
}

